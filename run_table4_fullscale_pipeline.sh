#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Full-scale defaults (can override by env)
export TRAIN_COUNT="${TRAIN_COUNT:-1500}"
export TEST_COUNT="${TEST_COUNT:-500}"
export SEED="${SEED:-42}"

export SUDOKU_SIZES="${SUDOKU_SIZES:-16x16,25x25}"
export NQUEENS_SIZES="${NQUEENS_SIZES:-12,14,16}"
export TASKS="${TASKS:-all}"

export GEN_SUDOKU_SIZES="${GEN_SUDOKU_SIZES:-$SUDOKU_SIZES}"
export NQUEENS_SIZES="${NQUEENS_SIZES:-$NQUEENS_SIZES}"

export GEN_SUDOKU_GPUS="${GEN_SUDOKU_GPUS:-0,1,2,3,4,5,6,7}"
export NQUEENS_GPUS="${NQUEENS_GPUS:-0,1,2,3,4,5,6,7}"
export GPUS="${GPUS:-0,1,2,3,4,5,6,7}"
export MODEL_DEVICE="${MODEL_DEVICE:-cuda}"
export WORKERS="${WORKERS:-8}"

export GEN_SUDOKU_EPOCHS="${GEN_SUDOKU_EPOCHS:-60}"
export NQUEENS_EPOCHS="${NQUEENS_EPOCHS:-60}"
export GEN_SUDOKU_BATCH_SIZE="${GEN_SUDOKU_BATCH_SIZE:-32}"
export NQUEENS_BATCH_SIZE="${NQUEENS_BATCH_SIZE:-64}"
export GEN_SUDOKU_LR="${GEN_SUDOKU_LR:-3e-4}"
export NQUEENS_LR="${NQUEENS_LR:-3e-4}"
export GEN_SUDOKU_WORKERS="${GEN_SUDOKU_WORKERS:-8}"
export NQUEENS_WORKERS="${NQUEENS_WORKERS:-8}"
export GEN_SUDOKU_HIDDEN_SIZE="${GEN_SUDOKU_HIDDEN_SIZE:-640}"
export NQUEENS_HIDDEN_SIZE="${NQUEENS_HIDDEN_SIZE:-640}"
export GEN_SUDOKU_NUM_LAYERS="${GEN_SUDOKU_NUM_LAYERS:-8}"
export NQUEENS_NUM_LAYERS="${NQUEENS_NUM_LAYERS:-8}"
export GEN_SUDOKU_NUM_HEADS="${GEN_SUDOKU_NUM_HEADS:-8}"
export NQUEENS_NUM_HEADS="${NQUEENS_NUM_HEADS:-8}"
export GEN_SUDOKU_GRAD_ACC_STEPS="${GEN_SUDOKU_GRAD_ACC_STEPS:-2}"
export NQUEENS_GRAD_ACC_STEPS="${NQUEENS_GRAD_ACC_STEPS:-1}"
export GEN_SUDOKU_LR_SCHEDULER="${GEN_SUDOKU_LR_SCHEDULER:-cosine}"
export NQUEENS_LR_SCHEDULER="${NQUEENS_LR_SCHEDULER:-cosine}"
export GEN_SUDOKU_WARMUP_RATIO="${GEN_SUDOKU_WARMUP_RATIO:-0.03}"
export NQUEENS_WARMUP_RATIO="${NQUEENS_WARMUP_RATIO:-0.03}"
export GEN_SUDOKU_MAX_GRAD_NORM="${GEN_SUDOKU_MAX_GRAD_NORM:-1.0}"
export NQUEENS_MAX_GRAD_NORM="${NQUEENS_MAX_GRAD_NORM:-1.0}"

export TIMEOUT_MS="${TIMEOUT_MS:-60000}"
export MAX_NODES="${MAX_NODES:-1000000}"
export ALPHA="${ALPHA:-0.8}"
export SMART_INTERVAL="${SMART_INTERVAL:-5}"
export MAX_GEN_ATTEMPTS="${MAX_GEN_ATTEMPTS:-4000000}"
export ALLOW_DUPLICATES="${ALLOW_DUPLICATES:-0}"
export SKIP_EXTERNAL_DISCOVER="${SKIP_EXTERNAL_DISCOVER:-1}"
export GENERATION_WORKERS="${GENERATION_WORKERS:-32}"
export UNIQUE_CHECK="${UNIQUE_CHECK:-1}"
export TRAIN_UNIQUE_CHECK="${TRAIN_UNIQUE_CHECK:-1}"
export TEST_UNIQUE_CHECK="${TEST_UNIQUE_CHECK:-1}"
export DATA_PROGRESS_EVERY="${DATA_PROGRESS_EVERY:-200}"
export DIFFICULTY_STRATIFICATION="${DIFFICULTY_STRATIFICATION:-0}"
export GENERATION_DIFFICULTY="${GENERATION_DIFFICULTY:-easy}"

export RESUME="${RESUME:-0}"
export RUN_ID="${RUN_ID:-}"
export RUNS_ROOT="${RUNS_ROOT:-$ROOT/experiments/table4_fullscale_runs}"

echo "============================================================"
echo "Table4 Full-Scale Pipeline (Run-Centric)"
echo "============================================================"
echo "RUNS_ROOT         : $RUNS_ROOT"
echo "RUN_ID            : ${RUN_ID:-<auto>}"
echo "TRAIN_COUNT       : $TRAIN_COUNT"
echo "TEST_COUNT        : $TEST_COUNT"
echo "SUDOKU_SIZES      : $SUDOKU_SIZES"
echo "NQUEENS_SIZES     : $NQUEENS_SIZES"
echo "WORKERS           : $WORKERS"
echo "GPUS              : $GPUS"
echo "MODEL_DEVICE      : $MODEL_DEVICE"
echo "SKIP_DISCOVER     : $SKIP_EXTERNAL_DISCOVER"
echo "GEN_WORKERS       : $GENERATION_WORKERS"
echo "UNIQUE(train/test): $TRAIN_UNIQUE_CHECK/$TEST_UNIQUE_CHECK (global=$UNIQUE_CHECK)"
