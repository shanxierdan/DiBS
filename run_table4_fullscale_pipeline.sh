echo "DIFF_STRATIFIED   : $DIFFICULTY_STRATIFICATION"
echo "GEN_DIFFICULTY    : $GENERATION_DIFFICULTY"
echo "GEN_SUDOKU_EPOCHS : $GEN_SUDOKU_EPOCHS"
echo "NQUEENS_EPOCHS    : $NQUEENS_EPOCHS"
