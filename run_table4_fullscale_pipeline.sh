echo "NQ  model         : h=$NQUEENS_HIDDEN_SIZE L=$NQUEENS_NUM_LAYERS H=$NQUEENS_NUM_HEADS bs=$NQUEENS_BATCH_SIZE ga=$NQUEENS_GRAD_ACC_STEPS"
echo "RESUME            : $RESUME"
echo "============================================================"

bash "$ROOT/run_table4_extension_pipeline.sh"
